# 11. SHAP Explainability (LSTM) - KernelExplainer (TF2 Compatible)
# -------------------------------------------------------------
# NOTE: KernelExplainer is model-agnostic but can be slow. We use a small background sample.
shap.initjs()

# Flatten time-series windows for KernelExplainer
X_train_flat = X_train.reshape((X_train.shape[0], -1))
X_test_flat = X_test.reshape((X_test.shape[0], -1))

# Pick a small background set (50 samples or fewer if not available)
bg_size = min(50, X_train_flat.shape[0])
bg_idx = np.random.choice(X_train_flat.shape[0], bg_size, replace=False)
background = X_train_flat[bg_idx]

# Define a prediction function that accepts flattened input
def predict_from_flat(x_flat):
    # x_flat shape: (n_samples, window*2)
    x_reshaped = x_flat.reshape((-1, WINDOW, 2))
    preds = lstm_model.predict(x_reshaped, verbose=0)
    return preds.ravel()

# Create KernelExplainer
explainer = shap.KernelExplainer(predict_from_flat, background)

# Explain first N test samples (keep N small)
N_EXPLAIN = min(20, X_test_flat.shape[0])
# nsamples controls speed/accuracy of approximation
shap_values = explainer.shap_values(X_test_flat[:N_EXPLAIN], nsamples=100)

# Build readable feature names: order matches flattening [t0_val, t0_exo, t1_val, t1_exo, ...]
feature_names = []
for t in range(WINDOW):
    # label with relative lag (t from oldest to newest)
    lag = WINDOW - t
    feature_names.append(f"value_t-{lag}")
    feature_names.append(f"exo_t-{lag}")

# Plot SHAP summary (be aware KernelExplainer returns a list; for single-output model shap_values is array)
if isinstance(shap_values, list) and len(shap_values) == 1:
    shap_v = shap_values[0]
else:
    shap_v = np.array(shap_values)

# summary_plot expects shape (samples, features)
shap.summary_plot(shap_v, X_test_flat[:N_EXPLAIN], feature_names=feature_names)